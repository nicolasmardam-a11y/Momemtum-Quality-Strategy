"""Compact markdown tables from data/derived/lp_markouts_cells.parquet -> analyses/lp_markouts/out/tables.md
Units: cents per share (share-weighted) unless stated; CI = wider of event- and week-cluster bootstrap 95%."""
import json, sys
import numpy as np, pandas as pd

C = pd.read_parquet("data/derived/lp_markouts_cells.parquet")
c = lambda v: "" if pd.isna(v) else f"{100*v:.2f}"
ci = lambda r, m: f"{c(getattr(r, m))} [{c(getattr(r, m+'_lo'))}, {c(getattr(r, m+'_hi'))}]"

COLS = [("trades", lambda r: f"{int(r.n_trades):,}"), ("events", lambda r: f"{int(r.n_events):,}"),
        ("effM", lambda r: c(r.effM)), ("moR10s", lambda r: c(r.moR10)), ("moM1m", lambda r: c(r.moM60)),
        ("moM5m", lambda r: c(r.moM300)), ("moM1h", lambda r: c(r.moM3600)), ("moM24h", lambda r: c(r.moM86400)),
        ("rsM5m [CI]", lambda r: ci(r, "rsM300")), ("rsR5m", lambda r: c(r.rsR300)), ("reb", lambda r: c(r.reb)),
        ("net5m [CI]", lambda r: ci(r, "netM300")), ("net5m queue", lambda r: c(r.netM300_q)),
        ("rs_res [CI]", lambda r: ci(r, "rsres")), ("RoC_res %", lambda r: "" if pd.isna(r.roc_res) else f"{100*r.roc_res:.2f}"),
        ("hold med h", lambda r: "" if pd.isna(r.hold_med_h) else f"{r.hold_med_h:.1f}")]


def table(df, title):
    hdr = "| cell | " + " | ".join(k for k, _ in COLS) + " |\n|" + "---|" * (len(COLS) + 1) + "\n"
    body = "".join("| " + str(r.cell) + " | " + " | ".join(f(r) for _, f in COLS) + " |\n" for r in df.itertuples())
    return f"\n**{title}**\n\n" + hdr + body


out = ["# lp_markouts tables (auto-generated by 03_tables.py)\n",
       "Cents per filled share, share-weighted. effM = effective half-spread vs the minute-series mid; moX_h = markout (adverse",
       "move in the taker's direction) at h with reference M (minute series) or R (print mid); rsM5m = realised spread at 5 m",
       "= maker trading P&L marked to mid; reb = current maker rebate; net5m = rsM5m + reb; queue = back-of-queue reweighting;",
       "rs_res = maker P&L if held to resolution; RoC_res = rs_res per $ committed. CI = wider of event- and week-cluster 95%.\n"]
sp = C[C.dim == "all"].copy(); sp["cell"] = sp.split
out.append(table(sp.set_index("split").loc[["train", "validation", "test"]].reset_index(), "All trades by split"))
dims = sys.argv[1:] or ["category", "pb", "ttr", "size", "game", "vol", "imb", "release", "fee_era"]
for dim in dims:
    for s in ["test", "validation", "train"] if dim in ("category", "pb") else ["test"]:
        sub = C[(C.dim == dim) & (C.split == s)]
        sub = sub[sub.n_trades >= 500]
        out.append(table(sub, f"{s.upper()} by {dim} (cells with >= 500 trades)"))
open("analyses/lp_markouts/out/tables.md", "w").write("\n".join(out))
print("written", len("\n".join(out)))
